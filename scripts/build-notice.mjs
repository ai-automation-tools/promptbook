#!/usr/bin/env node
// NOTICE's list of copied content, generated from each library item's `upstream:` block (PB-17),
// so a new source can't be added without the NOTICE naming it. The rest of NOTICE is hand-written;
// this script owns only the text between the two marker lines.
//
//   node scripts/build-notice.mjs           # exit 1 if NOTICE is out of date (upstream.test.mjs runs this check)
//   node scripts/build-notice.mjs --write   # rewrite the generated part
//
// An MIT source must carry its copyright line, which lives in COPYRIGHT below: take it from
// `gh api repos/<owner>/<repo>/license --jq .content | base64 -d`. Skills are counted, not
// listed: each keeps its source's licence text beside its SKILL.md.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const LIB = path.join(ROOT, "site", "library");
const NOTICE = path.join(ROOT, "NOTICE");
const BEGIN = "--- Copied content by source. Generated by scripts/build-notice.mjs; do not edit. ---";
const END = "--- End of generated list. ---";

/** The copyright line of each MIT-licensed source repo of agents, prompts and system prompts. */
