const LICENSE_NAME = { MIT: "MIT License", "Apache-2.0": "Apache License, Version 2.0" };

const walk = (d, out = []) => {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (e.name.endsWith(".md") && e.name.toLowerCase() !== "readme.md") out.push(p);
  }
  return out;
};
const field = (block, k) => block.match(new RegExp(`^\\s+${k}:\\s*(\\S+)`, "m"))?.[1];

/** The generated list, and the MIT sources missing a COPYRIGHT entry. */
export function renderSources() {
  const repos = new Map(); // repo -> { license, sections: Map<section, n> }
  const skillRepos = new Set();
  let skills = 0, vendor = 0;
  for (const section of ["2_Agents", "3_Skills", "4_Prompts", "5_System_Prompts"]) {
    for (const f of walk(path.join(LIB, section))) {
      const isSkill = path.basename(f) === "SKILL.md";
      if (section === "3_Skills" && !isSkill) continue;
      const block = fs.readFileSync(f, "utf8").replace(/\r\n/g, "\n").match(/^upstream:\n((?:[ \t]+.*\n?)*)/m)?.[1];
      if (!block) continue;
      if (field(block, "match") === "vendor") { vendor++; continue; }
      const repo = field(block, "repo");
      if (!repo) continue;
      if (isSkill) { skills++; skillRepos.add(repo); continue; }
      const r = repos.get(repo) ?? { license: field(block, "license") ?? "missing", sections: new Map() };
      r.sections.set(section, (r.sections.get(section) ?? 0) + 1);
      repos.set(repo, r);
    }
  }
  const missing = [];
  const lines = [BEGIN, ""];
  for (const [repo, r] of [...repos].sort(([a], [b]) => a.toLowerCase().localeCompare(b.toLowerCase()))) {
    const copyright = COPYRIGHT[repo];
    if (r.license === "MIT" && !copyright) missing.push(repo);
    const where = [...r.sections].map(([s, n]) => `${n} in site/library/${s}/`).join(", ");
    lines.push(`- ${repo}: ${LICENSE_NAME[r.license] ?? r.license}${copyright ? `, ${copyright}` : ""}`, `  ${where}`);
  }
  lines.push(
    "",
    `Skills: ${skills} from ${skillRepos.size} repositories, each with its source's licence`,
    "text beside its SKILL.md and named in its upstream: block.",
    `System prompts quoted from the vendor's own page: ${vendor}, licence NOASSERTION`,
    "(no licence is claimed for them; each names the page it was retrieved from).",
    "",
    END,
  );
  return { text: lines.join("\n"), missing };
}

/** NOTICE with its generated part replaced. */
export function noticeWith(sources) {
  const notice = fs.readFileSync(NOTICE, "utf8");
  const a = notice.indexOf(BEGIN), b = notice.indexOf(END);
  if (a === -1 || b === -1) throw new Error(`NOTICE lacks the marker lines:\n${BEGIN}\n${END}`);
  return { current: notice, next: notice.slice(0, a) + sources + notice.slice(b + END.length) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { text, missing } = renderSources();
  if (missing.length) {
    console.error(`No copyright line in scripts/build-notice.mjs COPYRIGHT for: ${missing.join(", ")}`);
    process.exit(1);
  }
  const { current, next } = noticeWith(text);
  if (process.argv.includes("--write")) {
    fs.writeFileSync(NOTICE, next);
    console.log(current === next ? "NOTICE already current" : "NOTICE rewritten");
  } else if (current !== next) {
    console.error("NOTICE is out of date: run node scripts/build-notice.mjs --write");
    process.exit(1);
  } else console.log("NOTICE is current");
}
